"""The published skills must describe the product that exists.

Audited 2026-11-21 against production: all six packs opened with `# Skill:` and no frontmatter, so
copying them into an agent's skills folder registered nothing; every one referred to per-method
functions such as `valuation_berkus`, which the library has never had; and after that was corrected,
the argument lists named the *function* parameters rather than the *MCP* arguments (`lambda_` where
the tool accepts `mean_events`), so a pack that loaded still told an agent to call tools in a way the
tool rejects.

Each test below corresponds to one of those failures:

* loadable — YAML frontmatter whose `description` actually has a body, and a `name` matching the
  directory;
* non-vacuous — every pack names at least one tool, so the checks over tool and method names cannot
  pass by finding nothing;
* real tools, real methods — derived from `tool_surface.py`, never listed here;
* real arguments — every documented parameter is one the tool's schema advertises;
* nothing stale anywhere — including the `/skills` page those packs link to, which carried the same
  non-existent names.

The scope of each pack is generated by `scripts/generate_skills.py` from that pack's summary line, so
this does not police which tools a pack covers; it only refuses names that do not exist.
"""

from __future__ import annotations

import pathlib
import re

from startup_valuation.mcp.tool_surface import TOOLS, input_schema

ROOT = pathlib.Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
PAGE = ROOT / "app" / "(en)" / "skills" / "page.tsx"

# mkdocs builds `docs/` into `public/docs` inside the web image, so these pages are served at
# /docs/ from the same digest as /skills. `troubleshooting.md` is excluded because it names
# non-tools deliberately, as the ❌ half of a spelling example.
DOCS_PAGES = [
    "index.md",
    "mcp-server.md",
    "agent-skills.md",
    "chapters.md",
    "notation.md",
    "cross-reference.md",
]
PUBLIC_PAGES = [ROOT / "public" / "llms.txt"]

# Tool name -> the method keys and the parameter names its schema advertises.
TOOL_NAMES = {tool["name"] for tool in TOOLS}
METHOD_KEYS = {tool["name"]: {m["key"] for m in tool["methods"]} for tool in TOOLS}
PARAMETERS = {tool["name"]: set(input_schema(tool)["properties"]) - {"method"} for tool in TOOLS}


def _packs() -> list[pathlib.Path]:
    return sorted(SKILLS.glob("*/SKILL.md"))


def _frontmatter(text: str) -> str:
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    return match.group(1) if match else ""


def _blocks(text: str) -> list[tuple[str, str]]:
    """(tool, block) for every `### `valuation_xxx`` heading, to the next heading of either level."""
    out = []
    for match in re.finditer(r"^### `(valuation_[a-z_]+)`$", text, re.M):
        rest = text[match.end() :]
        stop = re.search(r"^#{2,3} ", rest, re.M)
        out.append((match.group(1), rest[: stop.start()] if stop else rest))
    return out


def test_there_are_six_packs() -> None:
    packs = _packs()
    # A loop over zero files would satisfy every assertion below.
    assert len(packs) == 6, f"expected 6 skill packs, found {[p.parent.name for p in packs]}"


def test_every_pack_is_loadable() -> None:
    missing, mismatched, empty = [], [], []
    for path in _packs():
        meta = _frontmatter(path.read_text(encoding="utf-8"))
        name = re.search(r"^name:\s*(\S+)", meta, re.M)
        # `description: >-` alone matches a naive `\S+` capture and is an empty description.
        body = re.search(r"^description:\s*(?:[>|]-?\s*\n(?P<folded>(?:[ \t]+.*\n?)+)|(?P<inline>.+))", meta, re.M)
        text = ""
        if body:
            text = (body.group("folded") or body.group("inline") or "").strip()
        if not name or not text:
            missing.append(path.parent.name) if not name else empty.append(path.parent.name)
            continue
        if len(text) < 40:
            empty.append(path.parent.name)
        if name.group(1) != path.parent.name:
            mismatched.append((path.parent.name, name.group(1)))
    assert not missing, f"packs without a `name` in frontmatter: {missing}"
    assert not empty, f"packs whose `description` has no usable body: {empty}"
    assert not mismatched, f"frontmatter name does not match the directory: {mismatched}"


def test_every_pack_names_at_least_one_tool() -> None:
    bare = [p.parent.name for p in _packs() if not _blocks(p.read_text(encoding="utf-8"))]
    assert not bare, f"packs that name no tool at all, so the checks below are vacuous: {bare}"


def test_every_tool_named_is_real() -> None:
    bad = [
        (path.parent.name, tool)
        for path in _packs()
        for tool, _ in _blocks(path.read_text(encoding="utf-8"))
        if tool not in TOOL_NAMES
    ]
    assert not bad, f"skill sections naming a tool that does not exist: {bad}"


def test_every_method_named_belongs_to_its_tool() -> None:
    bad = []
    for path in _packs():
        for tool, block in _blocks(path.read_text(encoding="utf-8")):
            if tool not in METHOD_KEYS:
                continue  # reported by the previous test
            for key in re.findall(r'`method: "([a-z_]+)"`', block):
                if key not in METHOD_KEYS[tool]:
                    bad.append((path.parent.name, tool, key))
    assert not bad, f"method named under the wrong tool: {bad}"


def test_every_documented_argument_is_one_the_tool_accepts() -> None:
    # The defect this arm exists for: the packs listed the library's parameter names, and the tool
    # rejects them (`method 'poisson' requires parameter 'mean_events'`).
    bad = []
    for path in _packs():
        for tool, block in _blocks(path.read_text(encoding="utf-8")):
            if tool not in PARAMETERS:
                continue
            for line in block.splitlines():
                if not line.startswith("- `method:"):
                    continue
                named = line.split("—", 1)[1] if "—" in line else ""
                named = re.sub(r"\(optional:.*?\)", "", named)
                for word in re.findall(r"[a-z_][a-z0-9_]*", named):
                    if word in {"all", "optional", "no", "parameters"}:
                        continue
                    if word not in PARAMETERS[tool]:
                        bad.append((path.parent.name, tool, word))
    assert not bad, f"arguments the tool does not accept: {bad}"


def _generator():
    """The skills generator itself, so the test pins the renderer and not a second copy of it."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("gen_skills", ROOT / "scripts" / "generate_skills.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_each_argument_line_matches_the_method_it_names() -> None:
    # The previous version only asked whether each word appeared in the tool's *union* of
    # parameters, so `poisson — outcomes` would pass (outcomes belongs to another method).
    gen = _generator()
    bad = []
    for path in _packs():
        for tool, block in _blocks(path.read_text(encoding="utf-8")):
            if tool not in METHOD_KEYS:
                continue
            for line in block.splitlines():
                match = re.match(r'- `method: "([a-z_]+)"` — (.*)$', line)
                if not match:
                    continue
                key, rendered = match.group(1), match.group(2).strip()
                method = next((m for t in TOOLS if t["name"] == tool for m in t["methods"] if m["key"] == key), None)
                if method is None:
                    bad.append((path.parent.name, tool, key, "no such method", ""))
                    continue
                if rendered != gen._params(method):
                    bad.append((path.parent.name, tool, key, rendered, gen._params(method)))
    assert not bad, f"rendered argument lists that do not match the method: {bad[:3]}"


def test_every_tool_is_documented_in_some_pack() -> None:
    # `SCOPE` in the generator is transcribed by hand, so a new tool would otherwise be documented
    # nowhere and every check here would stay green.
    documented = {tool for path in _packs() for tool, _ in _blocks(path.read_text(encoding="utf-8"))}
    assert documented == TOOL_NAMES, f"tools in no skill pack: {sorted(TOOL_NAMES - documented)}"


def test_the_mcp_reference_documents_every_method() -> None:
    # `docs/mcp-server.md` is the fourth hand-maintained copy of this fact. It had drifted to 3 of 6
    # time-value methods and 3 of 4 CAPM methods; a missing row is invisible without this.
    doc = (ROOT / "docs" / "mcp-server.md").read_text(encoding="utf-8")
    missing = [
        (tool["name"], method["key"])
        for tool in TOOLS
        for method in tool["methods"]
        if f'`{method["key"]}`' not in doc
    ]
    assert not missing, f"methods absent from the reference: {missing}"


def test_every_parameter_in_the_reference_is_one_the_method_accepts() -> None:
    # A key-only check passes on the parameter defects this page actually had (`scenarios` where the
    # tool requires `pwerm_scenarios`), which is how that drift shipped twice.
    doc = (ROOT / "docs" / "mcp-server.md").read_text(encoding="utf-8")
    by_key: dict[str, dict] = {}
    for tool in TOOLS:
        for method in tool["methods"]:
            by_key.setdefault(method["key"], method)

    rows, bad = 0, []
    for line in doc.splitlines():
        match = re.match(r"\|\s*`([a-z_]+)`\s*\|(.*)\|\s*$", line)
        if not match:
            continue
        key, rest = match.group(1), match.group(2)
        if key not in by_key:  # a header row such as `| `method` value | ... |`
            continue
        cells = [c.strip() for c in rest.split("|")]
        names = re.findall(r"`([a-z_][a-z0-9_]*)`", cells[-1])
        if not names:
            continue
        method = by_key[key]
        allowed = set((method.get("args") or {}).values()) | set((method.get("opt") or {}).values())
        rows += 1
        bad += [(key, n, sorted(allowed)) for n in names if n not in allowed]
    assert rows >= 50, f"only {rows} method rows parsed — the column pattern would be vacuous"
    assert not bad, f"parameters the method does not accept: {bad[:3]}"


def test_no_stale_references_anywhere_they_are_published() -> None:
    # The packs and the page they link to; the page carried the same 15 non-existent names.
    surfaces = [(p.parent.name, p.read_text(encoding="utf-8")) for p in _packs()]
    for path in [PAGE, *(ROOT / "docs" / name for name in DOCS_PAGES), *PUBLIC_PAGES]:
        if path.exists():
            surfaces.append((str(path.relative_to(ROOT)), path.read_text(encoding="utf-8")))
    stale = [
        (where, token)
        for where, text in surfaces
        for token in set(re.findall(r"\bvaluation_[a-z_]+\b", text))
        if token not in TOOL_NAMES
    ]
    assert not stale, f"references to names that are not tools: {stale}"
